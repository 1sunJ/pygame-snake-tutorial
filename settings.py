# 게임 전체에서 공유하는 상수 설정 파일
# 이 값들을 바꾸면 게임 크기, 속도, 색상이 한 번에 바뀜

CELL_SIZE = 20          # 각 셀(칸) 하나의 픽셀 크기
COLS = 20               # 가로 칸 수
ROWS = 20               # 세로 칸 수
WIDTH  = COLS * CELL_SIZE   # 화면 가로 픽셀 (20 * 20 = 400)
HEIGHT = ROWS * CELL_SIZE   # 화면 세로 픽셀 (20 * 20 = 400)

FPS_INIT = 10           # 시작 속도: 초당 10프레임 = 뱀이 1초에 10칸 이동

BLACK = (0,   0,   0)
GREEN = (0, 200,   0)
RED   = (200,  0,   0)
WHITE = (255, 255, 255)
